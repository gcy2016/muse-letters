// 留言板的最近留言（给 3D 空间用：常驻按钮的红点、玄关软木板上的便利贴）。认人的规则和 app.js（留言板网页）一样。
// 每 10 分钟读一次 GitHub；带 ETag，没变化时 GitHub 回 304，不占访问次数。
//   import { watchBoard, markSeen, hasNew } from "./board-feed.js";
//   watchBoard(function (list) { ... });  // list：最新的在前，[{ number, who, cls, text, created_at, url }]；cls 和留言板网页的样式名一样：m0 / m1 / o0 / o1 / claude
//   hasNew(list)   // 有没有“上次打开留言板之后”的新留言
//   markSeen(list) // 打开过留言板了，红点消掉
var cfg = window.BOARD_CONFIG;
var m = location.hostname.match(/^([^.]+)\.github\.io$/i);
var seg = location.pathname.split("/")[1];
var owner = m && seg ? m[1] : cfg.owner;
var repo = m && seg ? seg : cfg.repo;
var MARK = "Muse留言", CLAUDE_MARK = "Claude留言";
var members = cfg.members.filter(function (x) { return x.login; });
var owners = cfg.owners || [];
var INTERVAL = 10 * 60 * 1000;
var CACHE = "muse-board-feed2:" + owner + "/" + repo;
var SEEN = "muse-board-seen:" + owner + "/" + repo;

function memberOf(login) {
  for (var i = 0; i < members.length; i++) if (members[i].login.toLowerCase() === String(login).toLowerCase()) return i;
  return -1;
}
function parseBody(body) {
  var lines = String(body || "").replace(/\r\n/g, "\n").split("\n");
  var mark = "", first = lines[0] ? lines[0].trim() : "";
  if (first === MARK || first === CLAUDE_MARK || owners.some(function (o) { return o.mark === first; })) { mark = first; lines.shift(); }
  if (lines[0] && /^署名[：:]/.test(lines[0])) lines.shift();
  var text = lines.join("\n").replace(/\n*---\n_Generated by \[Claude Code\]\([^)]*\)_\s*$/, "").trim();
  return { mark: mark, claude: mark === CLAUDE_MARK, text: text };
}
// issue → 一条留言；不是留言板的帖子返回 null
function toMsg(it) {
  if (it.pull_request || it.title.indexOf(cfg.titlePrefix) !== 0) return null;
  var p = parseBody(it.body), idx = memberOf(it.user.login);
  var bot = it.user.login === "github-actions[bot]" && p.claude;
  if (idx < 0 && !bot) return null;
  var who, cls;
  var oi = owners.findIndex(function (o) { return o.mark === p.mark && o.login.toLowerCase() === it.user.login.toLowerCase(); });
  if (p.claude) { who = "Claude"; cls = "claude"; }
  else if (oi >= 0) { who = owners[oi].name; cls = "o" + oi; }
  else { who = members[idx].name; cls = "m" + idx; }
  return { number: it.number, who: who, cls: cls, text: p.text, created_at: it.created_at, url: it.html_url };
}

function readCache() { try { return JSON.parse(localStorage.getItem(CACHE) || "null"); } catch (e) { return null; } }
async function fetchList() {
  var c = readCache();
  var headers = { Accept: "application/vnd.github+json" };
  if (c && c.etag) headers["If-None-Match"] = c.etag;
  var r = await fetch("https://api.github.com/repos/" + owner + "/" + repo + "/issues?state=open&sort=created&direction=desc&per_page=50", { headers: headers, cache: "no-cache" });
  if (r.status === 304 && c) return c.list;
  if (!r.ok) throw new Error("GitHub 返回 " + r.status);
  var list = (await r.json()).map(toMsg).filter(Boolean).slice(0, 20);
  try { localStorage.setItem(CACHE, JSON.stringify({ etag: r.headers.get("ETag"), list: list })); } catch (e) {}
  return list;
}

var subs = [], last = null, timer = null;
function emit() { subs.forEach(function (f) { f(last); }); }
export function refreshBoard() {
  return fetchList().then(function (list) { last = list; emit(); return list; }, function () { return last; });
}
export function watchBoard(fn) {
  subs.push(fn);
  if (last) fn(last);
  else { var c = readCache(); if (c) { last = c.list; fn(last); } } // 先用上次读到的，马上有东西看
  if (!timer) { refreshBoard(); timer = setInterval(refreshBoard, INTERVAL); }
}

function seen() { try { return +localStorage.getItem(SEEN) || 0; } catch (e) { return 0; } }
export function hasNew(list) {
  if (!list || !list.length) return false;
  var s = seen();
  if (!s) { markSeen(list); return false; } // 这台设备第一次用：之前的都算看过了
  return list[0].number > s;
}
export function markSeen(list) {
  if (!list || !list.length) return;
  try { localStorage.setItem(SEEN, String(Math.max(seen(), list[0].number))); } catch (e) {}
}
